"""Launch configurations decided offline, so no inference call ever tunes.

THE AUTOTUNER IS NOT GONE. It is still declared in full on both kernels --
same configs, same key, same `_prune_by_shared_memory`, same `_best_of_three`
-- and `MOBA_AUTOTUNE=1` makes it the live policy. Every number in this file
was produced by running it. What changed is *when* tuning happens, not
whether.

WHY NOT AUTOTUNE AT LAUNCH TIME. Autotuning picks the right numbers, but by
default it picks them at the wrong moment: the first launch at a new shape
races every candidate configuration and pays a compile plus a benchmark for
each. In a serving path that lands on a user's request, and it recurs whenever
a shape is seen for the first time. FlashMoBA does not do this either -- its
`decide_lg_block_m` is a five-entry lookup distilled from
`benchmarks/bench_flash_moba_attn.py`, which is its authors' own tuning runs
shipped as data.

So the tuning still happens, and still by measurement. It happens in
`bench/tune_table.py`, on a machine someone is paying attention to, and its
output is pasted here. That is also how a new card gets measured before its
numbers are committed -- and it has already earned its keep: the first
measuring run caught this file claiming `num_stages=2` for the forward when
the autotuner had been choosing 3 all along.

PRUNING TO ONE CONFIG WOULD NOT HAVE WORKED. The obvious cheaper change is to
keep `triton.autotune` and have `early_config_prune` return the single config
the table names. It does not help: the autotuner's fast path tests
`len(self.configs) > 1` against the *decorated* list, not the pruned one
(`triton/runtime/autotuner.py:215`), so a pruned-to-one launch still enters the
benchmark path and times that config. Zero benchmarking needs the decorator
gone, which is why this goes through `triton.heuristics` instead.

WHY LOOKUP BEATS AUTOTUNE ON ONE AXIS TOO. `triton.autotune`'s cache key can
only contain kernel arguments, and the tuned constants are chosen *before* the
launch, so sequence length was never in it: one configuration raced at S=1024
served S=65536, on a card where those are a mostly-idle machine and a saturated
one. A host-side table has no such restriction. `seq_len` is part of the key
here, bracketed by powers of two, because that is the axis autotune
structurally could not see.

WHAT A MISS DOES. Falls back to `DEFAULT`, which is measured rather than
invented -- GROUP=64 won on both cards this project has run on, and is what the
autotuner chose unprompted on each. A miss is therefore a mild loss, not a
cliff, which is what makes shipping a partial table honest.
`bench/tune_table.py --check` reports which shapes are still missing.

THE TABLE IS GENERATED. Do not hand-edit entries: regenerate them, so every
number keeps its provenance.
"""

import functools
import os

import torch

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

# Set to run the autotuner instead of reading this table. Used by
# `bench/tune_table.py` to produce the entries below, and by anyone measuring a
# card whose numbers are not in here yet.
AUTOTUNE_ENV = "MOBA_AUTOTUNE"

# Sequence-length brackets, low edge inclusive. A shape is assigned the largest
# bracket not above it, so a table built at powers of two answers for every
# length in between. Brackets rather than exact lengths because the tuned
# choice moves slowly with S -- and an exact key would miss on almost every
# real sequence.
SEQ_BRACKETS = (1024, 4096, 16384, 65536)

# What a miss gets. GROUP=64 and num_warps=4 are measured: the autotuner chose
# them on both sm_86 (laptop) and sm_80 (A100), forward and backward, across
# every shape tried, and `moba_fwd.AUTOTUNE_WARPS` records the warp sweep that
# put 4 within 0.7% of the best.
#
# num_stages is 3 because that is what the forward actually ran with. The first
# version of this file said 2, copied from the backward's `BWD_STAGES` on the
# assumption that the two passes matched. They do not: the forward's autotune
# configs never set `num_stages`, so Triton's own default of 3 applied and won
# every race this kernel has run. A default that is merely plausible is worse
# here than no default, because it sits beside measured entries and reads like
# one -- `bench/tune_table.py` caught this on its first measuring run.
#
# The backward wants 2 and says so in its own entries; per-pass values live in
# TUNED, and this is only the floor for a shape nobody has measured.
DEFAULT = {"GROUP": 64, "num_warps": 4, "num_stages": 3}


# ---------------------------------------------------------------------------
# The table
# ---------------------------------------------------------------------------

# Generated by `bench/tune_table.py`. Key is
# (arch, pass, block_size, key_tile, head_dim, top_k, h_q, h_kv, seq_bracket);
# `key_tile` is 0 for the forward, which has no such axis. Value is the winning
# config's kwargs plus its launch dimensions.
#
# Sparse by design: only shapes actually measured appear. Everything else takes
# DEFAULT and says so under `--check`.
TUNED: dict[tuple, dict] = {
    # sm_80, backward, block_size 128, key_tile 64, D 64, top_k 8, H 4/4.
    # Confirmed on the A100 by `bench/_small_s_dip.py`, which printed the
    # autotuner's choice at every bracket in that sweep and found one winner
    # across all of them: "GROUP: 64, num_warps: 4, num_stages: 2".
    ("sm_80", "bwd", 128, 64, 64, 8, 4, 4, 1024):
        {"GROUP": 64, "num_warps": 4, "num_stages": 2},
    ("sm_80", "bwd", 128, 64, 64, 8, 4, 4, 4096):
        {"GROUP": 64, "num_warps": 4, "num_stages": 2},
    ("sm_80", "bwd", 128, 64, 64, 8, 4, 4, 16384):
        {"GROUP": 64, "num_warps": 4, "num_stages": 2},

    # sm_86, block_size 128, D 64, top_k 8, H 4/4.
    # Measured by bench/tune_table.py on an RTX 3050 Ti Laptop GPU.
    ("sm_86", "bwd", 128, 64, 64, 8, 4, 4, 1024):
        {"GROUP": 64, "num_warps": 4, "num_stages": 2},
    ("sm_86", "bwd", 128, 64, 64, 8, 4, 4, 4096):
        {"GROUP": 64, "num_warps": 4, "num_stages": 2},
    ("sm_86", "fwd", 128, 0, 64, 8, 4, 4, 1024):
        {"GROUP": 64, "num_warps": 4, "num_stages": 3},
    ("sm_86", "fwd", 128, 0, 64, 8, 4, 4, 4096):
        {"GROUP": 64, "num_warps": 4, "num_stages": 3},
}


# ---------------------------------------------------------------------------
# Lookup
# ---------------------------------------------------------------------------


def autotune_requested() -> bool:
    """Reports whether this session should tune instead of reading the table."""
    return os.environ.get(AUTOTUNE_ENV, "0") == "1"


@functools.lru_cache(maxsize=None)
def capability_tag(device=None) -> str:
    """Returns this device's architecture as `sm_NM`.

    Cached because this sits on the launch path. Replacing `triton.autotune`
    with `triton.heuristics` moves config selection from once-per-shape to
    once-per-launch, so anything it calls has to be cheap -- and
    `torch.cuda.get_device_capability` is a driver query, not a field read. A
    process does not change GPU architecture mid-run, so the answer is
    permanent.

    The tuned choice is a property of the architecture, not of the board: an
    A100 and an A30 are both sm_80 and want the same tile. Keying on the device
    *name* would split entries that should share.

    Args:
        device: A torch device or index; defaults to the current one.

    Returns:
        For example "sm_80". Returns "sm_00" when no CUDA device is present,
        which misses every entry and takes DEFAULT rather than raising -- a
        table lookup is not the place to discover there is no GPU.
    """
    if not torch.cuda.is_available():
        return "sm_00"
    major, minor = torch.cuda.get_device_capability(device)
    return f"sm_{major}{minor}"


def seq_bracket(seq_len: int) -> int:
    """Returns the largest bracket at or below `seq_len`.

    Args:
        seq_len: The sequence length of this launch.

    Returns:
        A member of `SEQ_BRACKETS`; the smallest one for anything below it, so
        a short sequence keys to the shape the table was built for rather than
        missing.
    """
    eligible = [b for b in SEQ_BRACKETS if b <= seq_len]
    return max(eligible) if eligible else SEQ_BRACKETS[0]


def lookup(pass_name: str, *, block_size: int, head_dim: int, top_k: int,
           h_q: int, h_kv: int, seq_len: int, key_tile: int = 0,
           device=None) -> dict:
    """Returns the launch configuration for one kernel at one shape.

    Args:
        pass_name: "fwd" or "bwd".
        block_size: MoBA block size, the kernel's `BLOCK_SIZE`.
        head_dim: The kernel's `D`.
        top_k: Blocks selected per query, the kernel's `K_SLOTS`.
        h_q: Query head count.
        h_kv: Key/value head count.
        seq_len: Sequence length, bracketed before lookup.
        key_tile: The backward's `KEY_TILE`; 0 for the forward.
        device: Passed to `capability_tag`.

    Returns:
        A dict with "GROUP", "num_warps" and "num_stages". Always returns
        something: a miss yields a copy of `DEFAULT`, so a caller adjusting it
        for shared memory cannot corrupt the table.
    """
    return dict(_resolve(
        capability_tag(device), pass_name, block_size, key_tile, head_dim,
        top_k, h_q, h_kv, seq_bracket(seq_len)))


@functools.lru_cache(maxsize=None)
def _resolve(*key) -> dict:
    """Returns the table entry for a fully-built key, or `DEFAULT`.

    Split out and cached so the per-launch path is one dict hit on a tuple of
    ints. The returned dict is shared, which is why `lookup` copies it before
    handing it out.
    """
    return TUNED.get(key, DEFAULT)


def missing(pass_name: str, arch: str) -> list[tuple]:
    """Returns the brackets `bench/tune_table.py` has not filled for this pass.

    Used by `--check`, so a partial table is a known quantity rather than a
    silent one.

    Args:
        pass_name: "fwd" or "bwd".
        arch: An architecture tag such as "sm_80".

    Returns:
        Every bracket with no entry, as (arch, pass_name, bracket) triples.
    """
    have = {k[-1] for k in TUNED if k[0] == arch and k[1] == pass_name}
    return [(arch, pass_name, b) for b in SEQ_BRACKETS if b not in have]
